LINE_HEIGHT = 10
BASELINE = 7


def _rows(spec):
    rows = spec.split("/")
    width = max(len(r) for r in rows)
    rows = [r.ljust(width, ".") if r != "." else "." * width for r in rows]
    while len(rows) < 9:
        rows.append("." * width)
    return rows


GLYPHS = {ch: _rows(spec) for ch, spec in _G.items()}


def advance(ch, font=GLYPHS):
    return len(font.get(ch, font["?"])[0]) + 1


def width(s, font=GLYPHS):
    return sum(advance(ch, font) for ch in s) - 1 if s else 0


def build(out_dir):
    """Writes the font as a glyph sheet and an AngelCode BMFont text file."""
    from px import Canvas
    chars = [chr(i) for i in range(32, 127)]
    cell_w, cell_h, cols = 8, LINE_HEIGHT, 16
    sheet = Canvas(cell_w * cols, cell_h * ((len(chars) + cols - 1) // cols))
    lines = ['info face="Moelomol" size=%d bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0' % LINE_HEIGHT,
             "common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0" % (LINE_HEIGHT, BASELINE, sheet.w, sheet.h),
             'page id=0 file="moelomol_font.png"', "chars count=%d" % len(chars)]
    for n, ch in enumerate(chars):
        x, y = (n % cols) * cell_w, (n // cols) * cell_h
        rows = GLYPHS[ch]
        for j, row in enumerate(rows):
            for i, bit in enumerate(row):
                if bit == "#":
                    sheet.px(x + i, y + j, "X")
        lines.append("char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15"
                     % (ord(ch), x, y, len(rows[0]), 9, advance(ch)))
    sheet.save(out_dir + "/moelomol_font.png")
    with open(out_dir + "/moelomol_font.fnt", "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return len(chars)
